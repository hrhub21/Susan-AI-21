/**
 * Global Setup for Susan AI UI Tests
 * Prepares test environment and creates test data
 */

import { chromium } from '@playwright/test';
import fs from 'fs';
import path from 'path';

async function globalSetup() {
  console.log('🔧 Setting up UI test environment...');
  
  // Create test images directory
  const testImagesDir = path.join(process.cwd(), 'tests/test-data/images');
  if (!fs.existsSync(testImagesDir)) {
    fs.mkdirSync(testImagesDir, { recursive: true });
  }
  
  // Create test images if they don't exist
  await createTestImages(testImagesDir);
  
  // Verify server is accessible
  const browser = await chromium.launch();
  const context = await browser.newContext();
  const page = await context.newPage();
  
  try {
    // Wait for server to be ready
    let serverReady = false;
    for (let i = 0; i < 30; i++) {
      try {
        await page.goto('http://localhost:3001/roofing-analysis.html', { 
          timeout: 5000,
          waitUntil: 'domcontentloaded'
        });
        serverReady = true;
        break;
      } catch (error) {
        await new Promise(resolve => setTimeout(resolve, 2000));
      }
    }
    
    if (!serverReady) {
      throw new Error('Server not ready after 60 seconds');
    }
    
    console.log('✅ Server is ready for testing');
    
    // Verify API health
    try {
      const response = await page.evaluate(async () => {
        const resp = await fetch('/api/v1/photo-analysis/analyze-photo/health');
        return { status: resp.status, ok: resp.ok };
      });
      
      if (response.ok) {
        console.log('✅ API health check passed');
      } else {
        console.warn('⚠️ API health check failed, tests may fail');
      }
    } catch (error) {
      console.warn('⚠️ API health check error:', error.message);
    }
    
  } catch (error) {
    console.error('❌ Global setup failed:', error.message);
    throw error;
  } finally {
    await browser.close();
  }
  
  console.log('✅ Global setup complete');
}

async function createTestImages(testImagesDir) {
  const testImages = [
    {
      name: 'hail-damage-sample.jpg',
      content: createMinimalJPEG()
    },
    {
      name: 'wind-damage-sample.jpg',
      content: createMinimalJPEG()
    },
    {
      name: 'normal-roof-sample.jpg',
      content: createMinimalJPEG()
    },
    {
      name: 'non-roof-sample.jpg',
      content: createMinimalPNG()
    }
  ];
  
  for (const image of testImages) {
    const imagePath = path.join(testImagesDir, image.name);
    if (!fs.existsSync(imagePath)) {
      fs.writeFileSync(imagePath, image.content);
      console.log(`Created test image: ${image.name}`);
    }
  }
}

